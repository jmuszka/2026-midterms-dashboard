#!/usr/bin/env node
// Builds config/markets.json: maps each race id (S-TX, G-GA, H-VA-05 …) and the
// chamber-control questions to market ids on Kalshi, Polymarket and PredictIt.
// The live poller (lib/sources/markets.mjs) then only fetches prices for these ids.
//
// All three venues allow unauthenticated reads (docs/RESEARCH.md §3).
// Usage: node scripts/build-markets.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { partyId, raceId, STATES, matchCandidate } from '../lib/model.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0 Safari/537.36';
const { races } = JSON.parse(await fs.readFile(path.join(ROOT, 'config/races.json'), 'utf8'));
const raceIds = new Set(races.map((r) => r.id));
const byStateName = Object.fromEntries(Object.entries(STATES).map(([k, v]) => [v.name.toLowerCase(), k]));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function getJSON(url, tries = 3) {
  for (let i = 0; ; i++) {
    const res = await fetch(url, { headers: { 'user-agent': UA, accept: 'application/json' } });
    if (res.ok) return res.json();
    if (i >= tries - 1 || (res.status !== 429 && res.status < 500)) throw new Error(`${res.status} ${url}`);
    await sleep(1000 * (i + 1));
  }
}
async function pool(items, n, fn) {
  const out = []; let i = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (i < items.length) { const k = i++; out[k] = await fn(items[k]).catch((e) => ({ error: e.message })); } }));
  return out;
}
const partyOf = (s) => {
  const m = String(s).match(/\((D|R|I|L|G)\)|\b(Democratic|Democrats?|Dems?|Republicans?|GOP|Independent|Libertarian|Green)\b/i);
  if (!m) return null;
  const w = (m[1] || m[2]).replace(/s$/i, '');
  return /^dem$/i.test(w) ? 'DEM' : partyId(w);
};

const out = { _comment: 'GENERATED by scripts/build-markets.mjs. Race id -> market ids per venue.', generatedAt: new Date().toISOString(), control: {}, races: {} };
const raceById = Object.fromEntries(races.map((r) => [r.id, r]));
// a contract named after a person gets that candidate's party from the manifest
const fillParty = (id, e) => { if (!e.party && e.label) { const c = matchCandidate(e.label.replace(/\s*\(.*$/, ''), raceById[id]?.candidates || []); if (c) e.party = c.party; } return e; };
const add = (id, venue, entry) => { if (!raceIds.has(id)) return false;
  if (entry.contracts) entry.contracts.forEach((c) => fillParty(id, c)); else fillParty(id, entry); ((out.races[id] ||= {})[venue] ||= []).push(entry); return true; };

/* ---------------- Kalshi ---------------- */
const K = 'https://api.elections.kalshi.com/trade-api/v2';
out.control.S = { kalshi: [{ ticker: 'CONTROLS-2026-D', party: 'DEM' }, { ticker: 'CONTROLS-2026-R', party: 'GOP' }] };
out.control.H = { kalshi: [{ ticker: 'CONTROLH-2026-D', party: 'DEM' }, { ticker: 'CONTROLH-2026-R', party: 'GOP' }] };
const series = (await getJSON(`${K}/series?category=Elections&limit=3000`)).series;
const want = series.map((s) => s.ticker).map((t) => {
  let m;
  if ((m = t.match(/^SENATE([A-Z]{2})(S?)$/)) && STATES[m[1]]) return { t, id: raceId('S', m[1], null, m[2] === 'S') };
  if ((m = t.match(/^GOVPARTY([A-Z]{2})$/)) && STATES[m[1]]) return { t, id: raceId('G', m[1]) };
  if ((m = t.match(/^HOUSE([A-Z]{2})(\d+)$/)) && STATES[m[1]]) return { t, id: raceId('H', m[1], STATES[m[1]].seats === 1 ? 0 : +m[2]) };
  return null;
}).filter(Boolean);
let kalshiCount = 0;
await pool(want, 4, async ({ t, id }) => {
  const { events } = await getJSON(`${K}/events?series_ticker=${t}&status=open&with_nested_markets=true`);
  const ev = (events || []).find((e) => /-26$/.test(e.event_ticker));
  if (!ev) return;
  for (const m of ev.markets || []) {
    const suffix = m.ticker.split('-').pop();
    const party = { D: 'DEM', R: 'GOP', I: 'IND' }[suffix] || partyOf(m.yes_sub_title) || null;
    if (add(id, 'kalshi', { ticker: m.ticker, party, label: m.yes_sub_title || suffix })) kalshiCount++;
  }
});
// Same-race series named by candidate (KXMISENATE etc.) are skipped: the party series above covers them.

/* ---------------- Polymarket ---------------- */
const G = 'https://gamma-api.polymarket.com';
const events = [];
for (let offset = 0; offset < 2000; offset += 100) {
  const page = await getJSON(`${G}/events?tag_slug=midterms&closed=false&limit=100&offset=${offset}`);
  events.push(...page);
  if (page.length < 100) break;
}
const polyMarkets = (e) => e.markets.filter((m) => m.active && !m.closed && m.outcomePrices).map((m) => ({
  id: m.id, token: JSON.parse(m.clobTokenIds || '[]')[0] || null, label: m.groupItemTitle || m.question, party: partyOf(m.groupItemTitle) || partyOf(m.question),
}));
let polyCount = 0;
const unmatchedPoly = [];
for (const e of events) {
  let m, id = null;
  if (e.slug === 'which-party-will-win-the-senate-in-2026') { out.control.S.polymarket = polyMarkets(e); continue; }
  if (e.slug === 'which-party-will-win-the-house-in-2026') { out.control.H.polymarket = polyMarkets(e); continue; }
  if (e.slug === 'balance-of-power-2026-midterms') { out.control.combo = { polymarket: polyMarkets(e) }; continue; }
  if ((m = e.slug.match(/^([a-z-]+?)-senate-election-winner(?:-\d+)?$/))) {
    const st = byStateName[m[1].replace(/-/g, ' ')];
    if (st) id = raceIds.has(raceId('S', st)) ? raceId('S', st) : raceId('S', st, null, true);
  } else if ((m = e.slug.match(/^([a-z-]+?)-governor-(?:election-)?winner(?:-2026)?$/))) {
    const st = byStateName[m[1].replace(/-/g, ' ')];
    if (st) id = raceId('G', st);
  } else if ((m = e.slug.match(/^([a-z]{2})-(\d{2}|al)-house-election-winner(?:-(?:by-)?individual)?(?:-\d+)?$/))) {
    const st = m[1].toUpperCase();
    if (STATES[st]) id = raceId('H', st, m[2] === 'al' ? 0 : +m[2]);
  }
  if (!id) { if (/senate|governor|house/i.test(e.slug) && /winner/.test(e.slug)) unmatchedPoly.push(e.slug); continue; }
  for (const pm of polyMarkets(e)) if (add(id, 'polymarket', { ...pm, slug: e.slug })) polyCount++;
}

/* ---------------- PredictIt ---------------- */
const pi = await getJSON('https://www.predictit.org/api/marketdata/all/');
let piCount = 0;
const unmatchedPi = [];
for (const mk of pi.markets) {
  const n = mk.name;
  if (!/2026/.test(n) && !/202[67]/.test(mk.shortName)) continue;
  if (mk.contracts.some((c) => /%|\bby\b|margin/i.test(c.name))) continue; // margin brackets, not winner markets
  const contracts = mk.contracts.map((c) => ({ id: c.id, label: c.name, party: partyOf(c.name) || partyOf(c.shortName) }));
  if (/control the Senate/i.test(n)) { (out.control.S ||= {}).predictit = [{ market: mk.id, contracts }]; continue; }
  if (/control the House/i.test(n)) { (out.control.H ||= {}).predictit = [{ market: mk.id, contracts }]; continue; }
  let m, id = null;
  if ((m = n.match(/\b([A-Z]{2})-(\d{1,2}|AL)\b/)) && STATES[m[1]] && /House|district/i.test(n + mk.shortName)) id = raceId('H', m[1], m[2] === 'AL' ? 0 : +m[2]);
  else if ((m = n.match(/House (?:race|election) in ([A-Z][a-z]+(?: [A-Z][a-z]+)?)'s? (\d+)(?:st|nd|rd|th) District/)) && byStateName[m[1].toLowerCase()]) id = raceId('H', byStateName[m[1].toLowerCase()], +m[2]);
  else if ((m = n.match(/House (?:race|election) in ([A-Z][a-z]+(?: [A-Z][a-z]+)?)'s? at-large/i)) && byStateName[m[1].toLowerCase()]) id = raceId('H', byStateName[m[1].toLowerCase()], 0);
  else if ((m = n.match(/Senate (?:race|election)? ?in ([A-Z][a-z]+(?: [A-Z][a-z]+)?)/)) || (m = n.match(/([A-Z][a-z]+(?: [A-Z][a-z]+)?) Senate/))) {
    const st = byStateName[m[1].toLowerCase()];
    if (st) id = raceIds.has(raceId('S', st)) ? raceId('S', st) : raceId('S', st, null, true);
  } else if ((m = n.match(/governor(?:ship)? (?:race |election )?(?:of|in) ([A-Z][a-z]+(?: [A-Z][a-z]+)?)/i)) || (m = n.match(/([A-Z][a-z]+(?: [A-Z][a-z]+)?) gubernatorial/i))) {
    const st = byStateName[m[1].toLowerCase()];
    if (st) id = raceId('G', st);
  }
  if (!id) { if (/Senate|governor|House|district/i.test(n)) unmatchedPi.push(`${mk.id} ${n}`); continue; }
  if (add(id, 'predictit', { market: mk.id, contracts })) piCount++;
}

await fs.writeFile(path.join(ROOT, 'config/markets.json'), JSON.stringify(out, null, 1) + '\n');
const covered = Object.keys(out.races);
console.log(`wrote config/markets.json: ${covered.length} races with markets (kalshi ${kalshiCount} contracts, polymarket ${polyCount}, predictit ${piCount} markets)`);
for (const c of ['S', 'G']) {
  const all = races.filter((r) => r.chamber === c).map((r) => r.id);
  console.log(`${c}: ${all.filter((id) => out.races[id]).length}/${all.length} covered; missing: ${all.filter((id) => !out.races[id]).join(' ') || 'none'}`);
}
const tossups = races.filter((r) => r.chamber === 'H' && Math.abs(r.consensus?.score ?? 9) < 1.5).map((r) => r.id);
console.log(`competitive House: ${tossups.filter((id) => out.races[id]).length}/${tossups.length} covered; missing: ${tossups.filter((id) => !out.races[id]).join(' ')}`);
if (unmatchedPoly.length) console.log(`polymarket unmatched: ${unmatchedPoly.join(' ')}`);
if (unmatchedPi.length) console.log(`predictit unmatched:\n  ${unmatchedPi.join('\n  ')}`);
