// Builds public/favicon.svg: a red-and-blue map of the contiguous United States from
// public/data/states-10m.json (Albers equal-area, the contiguous part of d3's albersUsa).
// Colours are the 2024 presidential result by state: decorative only, never read by the app.
// Usage: node scripts/build-favicon.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import * as tc from 'topojson-client';
import * as ts from 'topojson-simplify';

const BLUE = '#3A7BE0', RED = '#E0453A';
const DEM = new Set(['53', '41', '06', '35', '08', '27', '17', '51', '24', '10', '34', '36', '09', '44', '25', '50', '33', '23', '11']);
const SKIP = new Set(['02', '15', '72', '78', '66', '69', '60']); // AK, HI and territories: too small at 32 px

let topo = JSON.parse(readFileSync(new URL('../public/data/states-10m.json', import.meta.url)));
topo = ts.simplify(ts.presimplify(topo), ts.quantile(ts.presimplify(topo), 0.997));

// Albers conic equal-area, standard parallels 29.5/45.5, origin -96/23 (d3's US defaults)
const rad = Math.PI / 180, p1 = 29.5 * rad, p2 = 45.5 * rad, lon0 = -96 * rad, lat0 = 23 * rad;
const n = (Math.sin(p1) + Math.sin(p2)) / 2, C = Math.cos(p1) ** 2 + 2 * n * Math.sin(p1);
const rho = (lat) => Math.sqrt(C - 2 * n * Math.sin(lat)) / n, rho0 = rho(lat0);
const project = ([lon, lat]) => { const th = n * (lon * rad - lon0), r = rho(lat * rad); return [r * Math.sin(th), r * Math.cos(th) - rho0]; /* SVG y grows downward */ };

const feats = tc.feature(topo, topo.objects.states).features.filter((f) => !SKIP.has(f.id));
const rings = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates);
let minX = 1e9, minY = 1e9, maxX = -1e9, maxY = -1e9;
const shapes = feats.map((f) => {
  const polys = rings(f.geometry).map((poly) => poly.map((ring) => ring.map(project)));
  for (const poly of polys) for (const ring of poly) for (const [x, y] of ring) { minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y); }
  return { id: f.id, polys };
});
const S = 32, scale = S / Math.max(maxX - minX, maxY - minY);
const ox = (S - (maxX - minX) * scale) / 2, oy = (S - (maxY - minY) * scale) / 2;
const fmt = (v) => Math.round(v * 10) / 10;
// at 32 px most 10m vertices collapse onto the same tenth of a pixel: drop repeats and specks
const d = (polys) => polys.map((poly) => poly.map((ring) => {
  const pts = []; let last = '';
  for (const [x, y] of ring) { const k = `${fmt((x - minX) * scale + ox)} ${fmt((y - minY) * scale + oy)}`; if (k !== last) pts.push(k); last = k; }
  return pts.length < 4 ? '' : 'M' + pts.join('L') + 'Z';
}).join('')).join('');
const paths = shapes.map((s) => `<path fill="${DEM.has(s.id) ? BLUE : RED}" d="${d(s.polys)}"/>`).join('\n');
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}">
<!-- generated by scripts/build-favicon.mjs: contiguous US, 2024 presidential result by state -->
<g stroke="#0e1116" stroke-width=".35" stroke-linejoin="round">
${paths}
</g>
</svg>
`;
writeFileSync(new URL('../public/favicon.svg', import.meta.url), svg);
console.log(`favicon.svg: ${shapes.length} states, ${svg.length} bytes`);
